"use client";

import { useState } from "react";

interface AnalysisItem {
  clause: string;
  risk_level: "High" | "Medium" | "Low";
  translation: string;
  counter_offer?: string;
}

interface DashboardProps {
  analysis: AnalysisItem[];
  onReset: () => void;
}

export default function AnalysisDashboard({
  analysis,
  onReset,
}: DashboardProps) {
  const [selectedOffer, setSelectedOffer] = useState<string | null>(null);

  const highRisks = analysis.filter(
    (item) => item.risk_level === "High"
  ).length;

  return (
    <div className="w-full max-w-3xl">

      {/* Header */}
      <div className="mb-8 flex items-end justify-between border-b border-zinc-800 pb-5">
        <div>
          <p className="text-xs uppercase tracking-widest text-zinc-500">
            Analysis complete
          </p>

          <h2 className="mt-2 text-2xl font-semibold text-white">
            Contract findings
          </h2>

          <p className="mt-1 text-sm text-zinc-500">
            {analysis.length} potential issues found
            {highRisks > 0 && ` · ${highRisks} high risk`}
          </p>
        </div>

        <button
          onClick={onReset}
          className="rounded-md border border-zinc-800 px-3 py-2 text-xs text-zinc-400 transition hover:border-zinc-600 hover:text-white"
        >
          New contract
        </button>
      </div>

      {/* Risk cards */}
      <div className="space-y-4">
        {analysis.map((item, index) => {
          const isHigh = item.risk_level === "High";

          return (
            <div
              key={index}
              className="rounded-lg border border-zinc-800 bg-zinc-900/30 p-5"
            >
              <div className="mb-4 flex items-start justify-between gap-4">
                <div className="flex items-center gap-3">
                  <span className="text-xs text-zinc-600">
                    {String(index + 1).padStart(2, "0")}
                  </span>

                  <span
                    className={`rounded px-2 py-1 text-[10px] font-semibold uppercase tracking-wider ${
                      isHigh
                        ? "bg-red-950/40 text-red-400"
                        : "bg-yellow-950/40 text-yellow-400"
                    }`}
                  >
                    {item.risk_level}
                  </span>
                </div>
              </div>

              <h3 className="text-base font-medium leading-6 text-white">
                {item.clause}
              </h3>

              <div className="mt-5 border-t border-zinc-800 pt-4">
                <p className="mb-2 text-[10px] font-medium uppercase tracking-widest text-zinc-600">
                  Plain-language explanation
                </p>

                <p className="text-sm leading-6 text-zinc-400">
                  {item.translation}
                </p>
              </div>

              {item.counter_offer && (
                <button
                  onClick={() => setSelectedOffer(item.counter_offer!)}
                  className="mt-5 text-xs font-medium text-zinc-300 underline decoration-zinc-700 underline-offset-4 transition hover:text-white"
                >
                  View suggested counter-offer
                </button>
              )}
            </div>
          );
        })}
      </div>

      {/* Bottom note */}
      <div className="mt-8 border-t border-zinc-800 pt-5 text-xs leading-5 text-zinc-600">
        This analysis is generated by an AI model and may contain errors.
        Review important contractual decisions with a qualified professional.
      </div>

      {/* Counter offer */}
      {selectedOffer && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-5">
          <div className="w-full max-w-xl rounded-lg border border-zinc-800 bg-zinc-950 p-6">

            <div className="mb-5 flex items-center justify-between">
              <h3 className="font-medium text-white">
                Suggested counter-offer
              </h3>

              <button
                onClick={() => setSelectedOffer(null)}
                className="text-sm text-zinc-500 hover:text-white"
              >
                Close
              </button>
            </div>

            <div className="rounded-md border border-zinc-800 bg-zinc-900 p-4 text-sm leading-6 text-zinc-300">
              {selectedOffer}
            </div>

            <button
              onClick={() => {
                navigator.clipboard.writeText(selectedOffer);
                setSelectedOffer(null);
              }}
              className="mt-4 w-full rounded-md bg-white py-2.5 text-sm font-medium text-black transition hover:bg-zinc-200"
            >
              Copy to clipboard
            </button>

          </div>
        </div>
      )}
    </div>
  );
}